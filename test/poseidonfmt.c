/* The Poseidon constants of circomlib 2.0.5 as a C table (S11 step 11.3, O101).
 *
 * build/poseidonfmt FILE reads the poseidon_constants.circom of circomlib 2.0.5
 * (the optimized form: POSEIDON_C, POSEIDON_S, POSEIDON_M and POSEIDON_P) and
 * prints src/front/poseidon_const.h on stdout. For t = 2 and t = 3 it prints each
 * table as 64-digit hex words in the order of the file. M and P are row-major:
 * the word at i * t + j is M[i][j]. The circom file is GPL-3.0 code. Only these
 * numbers, which are public parameters, enter the repo (O104). This is a
 * generator, not a test: `make check` does not run it. */
#include <ctype.h>
#include <stdio.h>
#include <string.h>

#define MAX_LINE 4096
#define HEX_DIGITS 64
#define TABLES 4
#define WIDTHS 2
#define MAX_WORDS 285

typedef char Hex[HEX_DIGITS + 1];

static const char names[TABLES] = {'C', 'S', 'M', 'P'};
/* The word count of each table for t = 2 and t = 3: C is t * 8 + nRoundsP, S is
 * nRoundsP * (2t - 1), M and P are t * t. nRoundsP is 56 for t = 2 and 57 for
 * t = 3 (N_ROUNDS_P of poseidon.circom). */
static const size_t expect[TABLES][WIDTHS] = {{72, 81}, {168, 285}, {4, 9}, {4, 9}};

static Hex table[TABLES][WIDTHS][MAX_WORDS];
static size_t count[TABLES][WIDTHS];

static int table_of(char name) {
  const char *at = memchr(names, name, TABLES);
  return at != NULL ? (int)(at - names) : -1;
}

/* Store each 0x word of line in the current table. Return 0 on a word that is
 * too long or on a table that is full. */
static int take_words(const char *line, int which, int width) {
  const char *p = line;
  int ok = 1;
  while (ok && (p = strstr(p, "0x")) != NULL) {
    p += 2;
    size_t len = strspn(p, "0123456789abcdefABCDEF");
    int keep = which >= 0 && width >= 0;
    ok = len > 0 && len <= HEX_DIGITS && (!keep || count[which][width] < MAX_WORDS);
    if (ok && keep) {
      char *out = table[which][width][count[which][width]++];
      size_t pad = HEX_DIGITS - len;
      memset(out, '0', pad);
      for (size_t i = 0; i < len; i++) out[pad + i] = (char)tolower((unsigned char)p[i]);
      out[HEX_DIGITS] = '\0';
    }
    p += len;
  }
  return ok;
}

/* The t of a test `(t==N)` or `(t == N)` in line: 2 or 3 give 0 or 1, another N
 * gives -1, and a line with no test gives -2. */
static int width_of(const char *line) {
  const char *p = strstr(line, "(t");
  if (p == NULL) return -2;
  p += 2 + strspn(p + 2, " ");
  if (strncmp(p, "==", 2) != 0) return -2;
  p += 2 + strspn(p + 2, " ");
  size_t len = strspn(p, "0123456789");
  return len == 1 && *p == '2' ? 0 : len == 1 && *p == '3' ? 1 : -1;
}

static int read_tables(FILE *in) {
  char line[MAX_LINE];
  int which = -1;
  int width = -1;
  int ok = 1;
  while (ok && fgets(line, sizeof line, in) != NULL) {
    const char *head = strstr(line, "function POSEIDON_");
    int test = width_of(line);
    ok = strchr(line, '\n') != NULL || feof(in);
    if (head != NULL) {
      which = table_of(head[strlen("function POSEIDON_")]);
      width = -1;
    } else if (test != -2) {
      width = test;
    } else if (strstr(line, "else") != NULL) {
      width = -1;
    }
    ok = ok && take_words(line, which, width);
  }
  return ok && ferror(in) == 0;
}

static int counts_ok(void) {
  int ok = 1;
  for (int w = 0; w < TABLES; w++)
    for (int k = 0; k < WIDTHS; k++)
      if (count[w][k] != expect[w][k]) {
        fprintf(stderr, "poseidonfmt: POSEIDON_%c(t=%d) has %zu words, not %zu\n", names[w], k + 2, count[w][k],
                expect[w][k]);
        ok = 0;
      }
  return ok;
}

static void print_tables(void) {
  printf("/* The Poseidon constants of circomlib 2.0.5 (S11 step 11.3, O101). Generated by\n"
         " * build/poseidonfmt (test/poseidonfmt.c) from poseidon_constants.circom. Do not\n"
         " * edit. Each word is 64 hex digits, big-endian. poseidon_cT, _sT, _mT and _pT\n"
         " * are POSEIDON_C(T), POSEIDON_S(T), POSEIDON_M(T) and POSEIDON_P(T); M and P\n"
         " * are row-major (the word at i * T + j is M[i][j]). */\n"
         "#ifndef SEALED_POSEIDON_CONST_H\n#define SEALED_POSEIDON_CONST_H\n");
  for (int k = 0; k < WIDTHS; k++)
    for (int w = 0; w < TABLES; w++) {
      printf("\nstatic const char *const poseidon_%c%d[%zu] = {\n", tolower((unsigned char)names[w]), k + 2,
             count[w][k]);
      for (size_t i = 0; i < count[w][k]; i++) printf("    \"%s\",\n", table[w][k][i]);
      printf("};\n");
    }
  printf("\n#endif\n");
}

int main(int argc, char **argv) {
  FILE *in = argc == 2 ? fopen(argv[1], "r") : NULL;
  if (in == NULL) {
    fprintf(stderr, "usage: poseidonfmt poseidon_constants.circom\n");
    return 2;
  }
  int ok = read_tables(in);
  fclose(in);
  if (!ok) {
    fprintf(stderr, "poseidonfmt: cannot read the tables (a long line or a long word)\n");
    return 1;
  }
  if (!counts_ok()) return 1;
  print_tables();
  return 0;
}
